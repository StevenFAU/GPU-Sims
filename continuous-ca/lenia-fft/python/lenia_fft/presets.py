def apply_preset(state: Any, preset: LeniaPreset) -> None:
    """Initialize a SimState's fields from a preset.

    Steps:
      1. Re-sample the kernel LUT for the preset's kernel_radius.
      2. Zero the state field.
      3. 2D: paste canonical RLE-decoded creature cells at the field center,
            over a quiescent field (polish-1; replaces the v1 random blob).
         3D: seed with a random blob (no canonical 3D creatures yet; preset is
             intentionally generic).
    """
    if preset.dim == 2:
        kernels.init_kernel_radial_2d(state.kernel_lut, preset.kernel_radius)
        # POLISH-1 (visual-verification gate): seed with canonical RLE-decoded
        # cells from animals.json, centered at the field's middle, over a
        # quiescent (all-zero) field. Random-blob seeding in Phase 10 v1 was
        # mathematically valid (attractor dynamics emerged) but did NOT show
        # recognizable canonical creatures — the user-runtime visual gate
        # surfaced this and round-3 smoke explicitly caveated it.
        kernels.init_state_zero_2d(state.state_2d)
        seed_2d = _SEED_CELLS_2D.get(preset.name)
        if seed_2d is None:
            # Defensive fallback for an as-yet-unseeded preset. Shouldn't fire
            # for the four shipped 2D presets (names match _SEED_CELLS_2D keys
            # byte-for-byte); guards against future preset additions before
            # their seed-cell extraction lands.
            log.warn(
                "preset %r has no canonical seed cells; falling back to random blob",
                preset.name,
            )
            kernels.init_state_random_blob_2d(
                state.state_2d,
                cx=float(state.n_grid) / 2.0,
                cy=float(state.n_grid) / 2.0,
                radius=preset.seed_radius_cells,
                n_grid=state.n_grid,
            )
        else:
            cells_np = np.array(seed_2d, dtype=np.float32)
            h, w = cells_np.shape
            top = (state.n_grid - h) // 2
            left = (state.n_grid - w) // 2
            full = np.zeros((state.n_grid, state.n_grid), dtype=np.float32)
            full[top:top + h, left:left + w] = cells_np
            state.state_2d.from_numpy(full)
    else:
        kernels.init_kernel_radial_3d(state.kernel_lut_3d, preset.kernel_radius)
        kernels.init_state_zero_3d(state.state_3d)
        kernels.init_state_random_blob_3d(
            state.state_3d,
            cx=float(state.n_grid) / 2.0,
            cy=float(state.n_grid) / 2.0,
            cz=float(state.n_grid) / 2.0,
            radius=preset.seed_radius_cells,
            n_grid=state.n_grid,
        )
